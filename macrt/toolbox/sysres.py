def pattern_list(patterns: list[str]) -> bytes:
    """A PAT#: the count, then each pattern's eight rows."""
    pats = [pattern(p) for p in patterns]
    return struct.pack(">H", len(pats)) + b"".join(pats)


def pattern(rows: str) -> bytes:
    """A 'PAT ': its eight rows."""
    return bytes(_bits(rows.split()))


