def fond(family: int, sizes: tuple[int, ...], ids: tuple[int, ...] = ()) -> bytes:
    """A font family record (Inside Macintosh IV-36): the header, with no
    width, kerning or style tables, and the font association table, a
    plain font for each size, numbered as a FONT would be unless ids says."""
    header = struct.pack(">8h3l9h2hh", 0, family, 0, 255, 0, 0, 0, 0, 0, 0, 0,
                         *[0] * 9, 0, 0, 1)
    ids = ids or tuple(family << 7 | size for size in sizes)
    table = struct.pack(">h", len(sizes) - 1) + b"".join(
        struct.pack(">3h", size, 0, rid) for size, rid in zip(sizes, ids))
    return header + table


def fonts() -> list[tuple[str, int, bytes, str]]:
    return [("FOND", family, fond(family, sizes), name)
            for family, (name, sizes) in FONTS.items()]


