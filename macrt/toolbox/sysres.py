AUTO_POP = 0x0400


def _pack_trap(n: int) -> int:
    return 0xA9E7 + n if n < 8 else 0xA816 if n == 8 else 0xA82B + n - 9


def package(n: int) -> bytes:
    """PACK n's code: _Packn with auto-pop, so that a program that calls
    into the package itself makes the same call as through the trap."""
    return (_pack_trap(n) | AUTO_POP).to_bytes(2, "big")


def _bits(rows: list[str]) -> list[int]:
    return [int(r.replace(".", "0").replace("#", "1"), 2) for r in rows]


def _icon(rows: list[str]) -> bytes:
    return b"".join(row.to_bytes(4, "big") for row in _bits(rows))


