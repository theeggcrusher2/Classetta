def _cursor(rows: list[str], hot_v: int, hot_h: int) -> bytes:
    """A CURS: the picture, then its mask (the picture filled in, with a
    white edge a pixel wide), then the hot spot."""
    data = _bits(rows)
    # Fill: whatever can't be reached from the edge without crossing the
    # picture is inside it.
    outside: set[tuple[int, int]] = set()
    todo = [(x, y) for x in range(16) for y in (0, 15)] + \
        [(x, y) for y in range(16) for x in (0, 15)]
    while todo:
        x, y = todo.pop()
        if (x, y) in outside or not (0 <= x < 16 and 0 <= y < 16) or rows[y][x] == "#":
            continue
        outside.add((x, y))
        todo += [(x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)]
    solid = [{x for x in range(16) if (x, y) not in outside} for y in range(16)]
    mask = [sum(0x8000 >> x for x in range(16)
                if any(nx in solid[ny] for nx in (x - 1, x, x + 1)
                       for ny in (y - 1, y, y + 1) if 0 <= ny < 16))
            for y in range(16)]
    return b"".join(w.to_bytes(2, "big") for w in data + mask + [hot_v, hot_h])


