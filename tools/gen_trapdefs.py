"""Generate macrt/m68k/trapdefs.py from the Multiversal Interfaces.

    git clone https://github.com/autc04/multiversal
    python tools/gen_trapdefs.py multiversal

The Multiversal Interfaces describe every classic Mac OS trap: its number,
its arguments and where each one lives (on the Pascal stack, in a register
or in a bit of the trap word).  macrt keeps the part it needs to decode a
trap -- name, argument layout, result -- as plain Python data, so a trap
the runtime doesn't implement yet can still be logged by name and have its
arguments popped.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

HEADER = '''\
"""Classic Mac OS trap signatures, generated by tools/gen_trapdefs.py.

Do not edit: regenerate from the Multiversal Interfaces instead.

Stack arguments are listed in declaration order (Pascal pushes them left to
right, so the last one is on top of the stack).  Each is one character:

    b  signed byte in a word slot, value in the high byte (Boolean, SignedByte)
    B  unsigned byte in a word slot
    h  INTEGER             H  unsigned 16-bit
    l  LONGINT             L  unsigned 32-bit (ResType, OSType, ...)
    p  pointer, handle or procedure pointer
    P  Point, passed by value (v then h)

A result uses the same characters, plus e for an OSErr and E for an
OSStatus (32 bits); "" is a procedure.  Register arguments
are (register, code) pairs: D0, D1, A0, A1, D0LowWord, D0HighWord,
TrapBit<mask>, Out<reg> and InOut<reg>.

FUNCTIONS maps a name to
    (trap, dispatcher, selector, stack_args, result, reg_args, result_reg, extras)
DISPATCHERS maps a dispatcher name to (trap, selector_location), and
TRAP_NAMES names the trap words the interfaces list as _Name constants,
whether or not a function above describes them.

Derived from the Multiversal Interfaces, https://github.com/autc04/multiversal
(%(revision)s), under this licence:

%(licence)s"""

# fmt: off
'''

SKIP_QUALIFIERS = {("api", "carbon"), ("only-for", "Executor-ppc")}


def preferred(item: dict) -> tuple[bool, int]:
    """(keep, rank): Executor's own view of a trap is the trap-level one."""
    if item.get("api") == "carbon":
        return False, 0
    only = str(item.get("only-for", "")).lower()
    if only and only != "executor":
        return False, 0
    if only == "executor":
        return True, 2
    if str(item.get("not-for", "")).lower() == "executor":
        return True, 0
    return True, 1


class Types:
    def __init__(self) -> None:
        self.typedefs: dict[str, str] = {}
        self.structs: dict[str, int | None] = {}
        self.funptrs: set[str] = set()
        self.enums: set[str] = set()

    def resolve(self, t: str) -> str:
        seen = set()
        t = t.replace("const ", "").strip()
        while t in self.typedefs and t not in seen and not t.endswith("*"):
            seen.add(t)
            t = self.typedefs[t].replace("const ", "").strip()
        return t

    def code(self, t: str, where: str) -> str:
        base = self.resolve(t)
        if base.endswith("*") or base.endswith("]") or base in self.funptrs \
                or base.endswith("UPP") or base.endswith("ProcPtr"):
            return "p"
        simple = {
            "int8_t": "b", "char": "b", "bool": "b", "uint8_t": "B",
            "int16_t": "h", "uint16_t": "H", "int32_t": "l", "uint32_t": "L",
            "Point": "P",
        }
        if base in simple:
            return simple[base]
        if base in self.enums:
            return "h"
        raise ValueError(f"{where}: can't place type {t!r} (resolves to {base!r})")


def main(root: str) -> None:
    root_path = Path(root)
    types = Types()
    functions: dict[str, tuple[int, dict]] = {}
    dispatchers: dict[str, tuple[int, str]] = {}
    trap_names: dict[int, str] = {}
    entries = []
    for f in sorted((root_path / "defs").glob("*.yaml")):
        for item in yaml.safe_load(f.read_text()) or []:
            keep, rank = preferred(item)
            if not keep:
                continue
            for kind in ("typedef", "struct", "union", "funptr", "enum",
                         "function", "dispatcher"):
                if kind in item:
                    entries.append((kind, item[kind], rank, f.stem))
    for kind, v, rank, _ in entries:
        if kind == "typedef":
            types.typedefs.setdefault(v["name"], v["type"])
        elif kind in ("struct", "union"):
            types.structs[v["name"]] = v.get("size")
        elif kind == "funptr":
            types.funptrs.add(v["name"])
        elif kind == "enum":
            if v.get("name"):
                types.enums.add(v["name"])
            for value in v.get("values") or []:
                n, x = value.get("name", ""), value.get("value")
                if n.startswith("_") and isinstance(x, int) and 0xA000 <= x <= 0xAFFF:
                    trap_names.setdefault(x, n[1:])
    for kind, v, rank, stem in entries:
        if kind == "dispatcher":
            dispatchers[v["name"]] = (v["trap"], v["selector-location"])
        elif kind == "function" and ("trap" in v or "dispatcher" in v):
            if v["name"] in functions and functions[v["name"]][0] >= rank:
                continue
            functions[v["name"]] = (rank, v)

    out = {}
    for name, (_, v) in sorted(functions.items()):
        where = f"{name}"
        stack, regs = [], []
        for a in v.get("args") or []:
            c = types.code(a["type"], where)
            if "register" in a:
                regs.append((a["register"], c))
            else:
                stack.append(c)
        result = ""
        ret = v.get("return")
        if ret in ("OSErr", "OSStatus", "ComponentResult"):
            result = "e" if ret == "OSErr" else "E"
        elif ret and ret != "void":
            result = types.code(ret, where)
        disp = v.get("dispatcher")
        trap = v.get("trap") or dispatchers[disp][0]
        extras = str(v.get("executor_extras", "")).replace("callconv::", "")
        out[name] = (trap, disp, v.get("selector"), "".join(stack), result,
                     tuple(regs), v.get("returnreg"), extras)

    revision = "unknown revision"
    head = root_path / ".git" / "HEAD"
    if head.exists():
        ref = head.read_text().strip()
        if ref.startswith("ref: "):
            ref_path = root_path / ".git" / ref[5:]
            ref = ref_path.read_text().strip() if ref_path.exists() else ref
        revision = f"commit {ref[:12]}"
    licence = (root_path / "COPYING").read_text().rstrip()
    text = HEADER % {"revision": revision, "licence": licence.replace('"""', "'''")}
    text += "\nFUNCTIONS = {\n"
    for name, (trap, disp, sel, stack, result, regs, rreg, extras) in out.items():
        sel_text = "None" if sel is None else hex(sel)
        text += (f"    {name!r}: (0x{trap:04X}, {disp!r}, {sel_text}, {stack!r}, "
                 f"{result!r}, {regs!r}, {rreg!r}, {extras!r}),\n")
    text += "}\n\nDISPATCHERS = {\n"
    for name, (trap, loc) in sorted(dispatchers.items()):
        text += f"    {name!r}: (0x{trap:04X}, {loc!r}),\n"
    text += "}\n\nTRAP_NAMES = {\n"
    for trap, name in sorted(trap_names.items()):
        text += f"    0x{trap:04X}: {name!r},\n"
    text += "}\n"
    dest = Path(__file__).resolve().parent.parent / "macrt" / "m68k" / "trapdefs.py"
    dest.write_text(text)
    print(f"wrote {len(out)} functions and {len(dispatchers)} dispatchers to {dest}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "multiversal")
